import { useEffect, useState } from "react";
import { fetchConfig } from "../api";

// Shown until the server answers, and kept if it never does.
export const DEFAULT_CONFIG = {
  app_name: "UI Postgraduate Assistant",
  tagline: "Answers about postgraduate study at the University of Ibadan, from official documents.",
  notice: "Answers are generated by AI from official documents and can be incomplete. Confirm important details with the Postgraduate College.",
  contact_email: "informationdesk@pgcollege.ui.edu.ng",
  contact_website: "https://pgcollege.ui.edu.ng",
  announcement: "",
  suggested_topics: [],
  model_choice: false,
  models: [],
  default_model: "",
};

const CACHE_KEY = "ui-pg-config";

// The last settings the server sent, so the home screen shows the right text at once (and offline).
function readCached() {
  try {
    return { ...DEFAULT_CONFIG, ...JSON.parse(localStorage.getItem(CACHE_KEY) || "{}") };
  } catch {
    return DEFAULT_CONFIG;
  }
}

export function useConfig() {
  const [config, setConfig] = useState(readCached);

  useEffect(() => {
    const controller = new AbortController();
    fetchConfig(controller.signal)
      .then((data) => {
        setConfig({ ...DEFAULT_CONFIG, ...data });
        try {
          localStorage.setItem(CACHE_KEY, JSON.stringify(data));
        } catch {
          // Storage can be blocked; the page then simply waits for the server each time.
        }
      })
      .catch(() => {});
    return () => controller.abort();
  }, []);

  return config;
}
