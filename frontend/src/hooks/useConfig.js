import { useEffect, useState } from "react";
import { fetchConfig } from "../api";

// Shown until the server answers, and kept if it never does.
export const DEFAULT_CONFIG = {
  app_name: "UI Postgraduate Assistant",
  tagline: "Answers about postgraduate study at the University of Ibadan, from official documents.",
  notice: "Answers are generated by AI from official documents and can be incomplete. Confirm important details with the Postgraduate College.",
  contact_email: "informationdesk@pgcollege.ui.edu.ng",
  contact_website: "https://pgcollege.ui.edu.ng",
  announcement: "",
  suggested_topics: [],
  model_choice: false,
  models: [],
  default_model: "",
};

export function useConfig() {
  const [config, setConfig] = useState(DEFAULT_CONFIG);

  useEffect(() => {
    const controller = new AbortController();
    fetchConfig(controller.signal)
      .then((data) => setConfig({ ...DEFAULT_CONFIG, ...data }))
      .catch(() => {});
    return () => controller.abort();
  }, []);

  return config;
}
